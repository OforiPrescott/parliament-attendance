-- =====================================================================
--  Parliament of Ghana — MP Attendance Management System
--  PostgreSQL 13+ schema
--
--  Design notes
--  * Every attendance row stores a SNAPSHOT of the MP's party and
--    constituency at the time of the sitting, so historical reports stay
--    correct after floor-crossing, by-elections or boundary changes.
--  * UNIQUE (sitting_id, mp_id) makes duplicate attendance impossible.
--  * Registers move DRAFT -> SUBMITTED -> APPROVED (or RETURNED). Approved
--    registers are locked; changes go through attendance_corrections.
--  * audit_logs is append-only. In production, grant the application
--    user INSERT + SELECT only on that table (see scripts/grants.sql).
--  * All timestamps are UTC, stored as TIMESTAMP WITHOUT TIME ZONE.
--  * Flag columns (is_active, …) are SMALLINT 0/1.
--  * Re-runnable: every statement is IF NOT EXISTS / ON CONFLICT DO NOTHING.
-- =====================================================================

SET client_min_messages = warning;

-- Keeps updated_at current on every UPDATE (MySQL's ON UPDATE CURRENT_TIMESTAMP).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := timezone('UTC', now());
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- Reference data
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS regions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(80)  NOT NULL,
  code        VARCHAR(10)  NULL,
  created_at  TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now())
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_regions_name ON regions (lower(name));

CREATE TABLE IF NOT EXISTS parties (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(150) NOT NULL,
  abbreviation  VARCHAR(20)  NOT NULL,
  color         CHAR(7)      NOT NULL DEFAULT '#6B7280',
  is_active     SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at    TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  updated_at    TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT ck_parties_color CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_parties_abbr ON parties (lower(abbreviation));
CREATE UNIQUE INDEX IF NOT EXISTS uq_parties_name ON parties (lower(name));

CREATE TABLE IF NOT EXISTS constituencies (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(150) NOT NULL,
  region_id   INTEGER      NOT NULL,
  code        VARCHAR(20)  NULL,
  is_active   SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at  TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  updated_at  TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT uq_constituency_code UNIQUE (code),
  CONSTRAINT fk_constituency_region FOREIGN KEY (region_id) REFERENCES regions(id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_constituency_name ON constituencies (lower(name));
CREATE INDEX IF NOT EXISTS ix_constituency_region ON constituencies (region_id);

-- ---------------------------------------------------------------------
-- Parliamentary calendar:  Parliament -> Session -> Meeting -> Sitting
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS parliaments (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number      SMALLINT     NOT NULL CHECK (number > 0),
  name        VARCHAR(120) NOT NULL,
  start_date  DATE NOT NULL,
  end_date    DATE NULL,
  is_current  SMALLINT NOT NULL DEFAULT 0 CHECK (is_current IN (0,1)),
  created_at  TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT uq_parliament_number UNIQUE (number),
  CONSTRAINT ck_parliament_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS parliament_sessions (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parliament_id  INTEGER  NOT NULL,
  number         SMALLINT NOT NULL CHECK (number > 0),
  name           VARCHAR(120) NOT NULL,
  start_date     DATE NOT NULL,
  end_date       DATE NULL,
  created_at     TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT uq_session UNIQUE (parliament_id, number),
  CONSTRAINT fk_session_parliament FOREIGN KEY (parliament_id) REFERENCES parliaments(id) ON DELETE RESTRICT,
  CONSTRAINT ck_session_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS meetings (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id  INTEGER  NOT NULL,
  number      SMALLINT NOT NULL CHECK (number > 0),
  name        VARCHAR(120) NOT NULL,
  start_date  DATE NOT NULL,
  end_date    DATE NULL,
  created_at  TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT uq_meeting UNIQUE (session_id, number),
  CONSTRAINT fk_meeting_session FOREIGN KEY (session_id) REFERENCES parliament_sessions(id) ON DELETE RESTRICT,
  CONSTRAINT ck_meeting_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS ix_meeting_dates ON meetings (start_date, end_date);

CREATE TABLE IF NOT EXISTS committees (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(150) NOT NULL,
  type        VARCHAR(10)  NOT NULL DEFAULT 'SELECT' CHECK (type IN ('STANDING','SELECT','AD_HOC')),
  is_active   SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at  TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  updated_at  TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now())
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_committee_name ON committees (lower(name));

-- ---------------------------------------------------------------------
-- Members of Parliament and their membership history
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mps (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parliamentary_id         VARCHAR(30)  NOT NULL,
  title                    VARCHAR(30)  NULL,
  first_name               VARCHAR(80)  NOT NULL,
  other_names              VARCHAR(120) NULL,
  last_name                VARCHAR(80)  NOT NULL,
  gender                   CHAR(1)      NOT NULL CHECK (gender IN ('M','F')),
  email                    VARCHAR(150) NULL,
  phone                    VARCHAR(30)  NULL,
  photo_path               VARCHAR(255) NULL,
  status                   VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE'
                             CHECK (status IN ('ACTIVE','SUSPENDED','RESIGNED','DECEASED','VACATED','FORMER')),
  current_party_id         INTEGER NULL,
  current_constituency_id  INTEGER NULL,
  created_at               TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  updated_at               TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT uq_mp_parl_id UNIQUE (parliamentary_id),
  CONSTRAINT fk_mp_party FOREIGN KEY (current_party_id) REFERENCES parties(id) ON DELETE SET NULL,
  CONSTRAINT fk_mp_constituency FOREIGN KEY (current_constituency_id) REFERENCES constituencies(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_mp_status ON mps (status);
CREATE INDEX IF NOT EXISTS ix_mp_name ON mps (last_name, first_name);
CREATE INDEX IF NOT EXISTS ix_mp_party ON mps (current_party_id);
CREATE INDEX IF NOT EXISTS ix_mp_constituency ON mps (current_constituency_id);

-- One row per continuous period an MP held a seat under one party.
-- Floor-crossing or a new Parliament closes the current row and opens a new one.
CREATE TABLE IF NOT EXISTS mp_memberships (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mp_id            INTEGER NOT NULL,
  parliament_id    INTEGER NOT NULL,
  party_id         INTEGER NOT NULL,
  constituency_id  INTEGER NOT NULL,
  start_date       DATE NOT NULL,
  end_date         DATE NULL,
  end_reason       VARCHAR(120) NULL,
  created_at       TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT fk_mem_mp FOREIGN KEY (mp_id) REFERENCES mps(id) ON DELETE CASCADE,
  CONSTRAINT fk_mem_parl FOREIGN KEY (parliament_id) REFERENCES parliaments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_mem_party FOREIGN KEY (party_id) REFERENCES parties(id) ON DELETE RESTRICT,
  CONSTRAINT fk_mem_const FOREIGN KEY (constituency_id) REFERENCES constituencies(id) ON DELETE RESTRICT,
  CONSTRAINT ck_mem_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS ix_mem_mp ON mp_memberships (mp_id, start_date);
CREATE INDEX IF NOT EXISTS ix_mem_active ON mp_memberships (start_date, end_date);

CREATE TABLE IF NOT EXISTS committee_members (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  committee_id  INTEGER NOT NULL,
  mp_id         INTEGER NOT NULL,
  role          VARCHAR(10) NOT NULL DEFAULT 'MEMBER' CHECK (role IN ('CHAIR','VICE_CHAIR','RANKING','MEMBER')),
  start_date    DATE NOT NULL,
  end_date      DATE NULL,
  CONSTRAINT uq_committee_member UNIQUE (committee_id, mp_id, start_date),
  CONSTRAINT fk_cm_committee FOREIGN KEY (committee_id) REFERENCES committees(id) ON DELETE CASCADE,
  CONSTRAINT fk_cm_mp FOREIGN KEY (mp_id) REFERENCES mps(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_cm_mp ON committee_members (mp_id);

-- ---------------------------------------------------------------------
-- Users, roles, sessions
-- Permissions per role are defined in code (src/lib/permissions.ts) so
-- they are version-controlled and reviewed; this table names the roles.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS roles (
  id           SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(30)  NOT NULL,
  name         VARCHAR(80)  NOT NULL,
  description  VARCHAR(255) NULL,
  CONSTRAINT uq_role_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS users (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username              VARCHAR(50)  NOT NULL,
  email                 VARCHAR(150) NOT NULL,
  full_name             VARCHAR(150) NOT NULL,
  role_id               SMALLINT NOT NULL,
  password_hash         VARCHAR(255) NOT NULL,
  is_active             SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  must_change_password  SMALLINT NOT NULL DEFAULT 1 CHECK (must_change_password IN (0,1)),
  failed_attempts       SMALLINT NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
  locked_until          TIMESTAMP(0) NULL,
  last_login_at         TIMESTAMP(0) NULL,
  password_changed_at   TIMESTAMP(0) NULL,
  created_at            TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  updated_at            TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT fk_user_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_username ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_email ON users (lower(email));

-- Session tokens are random 256-bit values; only their SHA-256 is stored.
CREATE TABLE IF NOT EXISTS user_sessions (
  id            CHAR(64) PRIMARY KEY,
  user_id       INTEGER NOT NULL,
  created_at    TIMESTAMP(0) NOT NULL,
  last_seen_at  TIMESTAMP(0) NOT NULL,
  expires_at    TIMESTAMP(0) NOT NULL,
  ip_address    VARCHAR(45)  NULL,
  user_agent    VARCHAR(255) NULL,
  revoked_at    TIMESTAMP(0) NULL,
  CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_session_user ON user_sessions (user_id);
CREATE INDEX IF NOT EXISTS ix_session_expiry ON user_sessions (expires_at);

-- ---------------------------------------------------------------------
-- Sittings and attendance
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sittings (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_id       INTEGER NULL,
  sitting_type     VARCHAR(10) NOT NULL DEFAULT 'PLENARY' CHECK (sitting_type IN ('PLENARY','COMMITTEE','OTHER')),
  committee_id     INTEGER NULL,
  title            VARCHAR(200) NOT NULL,
  sitting_date     DATE NOT NULL,
  start_time       TIME(0) NOT NULL,
  end_time         TIME(0) NULL,
  venue            VARCHAR(150) NULL,
  status           VARCHAR(10) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','HELD','ADJOURNED','CANCELLED')),
  register_status  VARCHAR(12) NOT NULL DEFAULT 'NOT_STARTED'
                     CHECK (register_status IN ('NOT_STARTED','DRAFT','SUBMITTED','RETURNED','APPROVED')),
  submitted_by     INTEGER NULL,
  submitted_at     TIMESTAMP(0) NULL,
  reviewed_by      INTEGER NULL,
  reviewed_at      TIMESTAMP(0) NULL,
  review_comment   VARCHAR(500) NULL,
  created_by       INTEGER NULL,
  created_at       TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  updated_at       TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT fk_sitting_meeting FOREIGN KEY (meeting_id) REFERENCES meetings(id) ON DELETE SET NULL,
  CONSTRAINT fk_sitting_committee FOREIGN KEY (committee_id) REFERENCES committees(id) ON DELETE RESTRICT,
  CONSTRAINT fk_sitting_submitter FOREIGN KEY (submitted_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_sitting_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_sitting_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT ck_sitting_committee CHECK (sitting_type <> 'COMMITTEE' OR committee_id IS NOT NULL),
  CONSTRAINT ck_sitting_times CHECK (end_time IS NULL OR end_time > start_time)
);
CREATE INDEX IF NOT EXISTS ix_sitting_date ON sittings (sitting_date);
CREATE INDEX IF NOT EXISTS ix_sitting_register ON sittings (register_status, sitting_date);
CREATE INDEX IF NOT EXISTS ix_sitting_type ON sittings (sitting_type, sitting_date);
CREATE INDEX IF NOT EXISTS ix_sitting_meeting ON sittings (meeting_id);
CREATE INDEX IF NOT EXISTS ix_sitting_committee ON sittings (committee_id);

CREATE TABLE IF NOT EXISTS attendance (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sitting_id       INTEGER NOT NULL,
  mp_id            INTEGER NOT NULL,
  party_id         INTEGER NULL,          -- snapshot at sitting date
  constituency_id  INTEGER NULL,          -- snapshot at sitting date
  status           VARCHAR(13) NOT NULL CHECK (status IN ('PRESENT','LATE','ABSENT','EXCUSED','OFFICIAL_DUTY')),
  arrival_time     TIME(0) NULL,
  remarks          VARCHAR(255) NULL,
  recorded_by      INTEGER NULL,
  recorded_at      TIMESTAMP(0) NOT NULL,
  updated_by       INTEGER NULL,
  updated_at       TIMESTAMP(0) NULL,
  CONSTRAINT uq_attendance UNIQUE (sitting_id, mp_id),
  CONSTRAINT fk_att_sitting FOREIGN KEY (sitting_id) REFERENCES sittings(id) ON DELETE CASCADE,
  CONSTRAINT fk_att_mp FOREIGN KEY (mp_id) REFERENCES mps(id) ON DELETE RESTRICT,
  CONSTRAINT fk_att_party FOREIGN KEY (party_id) REFERENCES parties(id) ON DELETE SET NULL,
  CONSTRAINT fk_att_const FOREIGN KEY (constituency_id) REFERENCES constituencies(id) ON DELETE SET NULL,
  CONSTRAINT fk_att_recorder FOREIGN KEY (recorded_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_att_updater FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_att_mp ON attendance (mp_id, sitting_id);
CREATE INDEX IF NOT EXISTS ix_att_party ON attendance (party_id);
CREATE INDEX IF NOT EXISTS ix_att_const ON attendance (constituency_id);
CREATE INDEX IF NOT EXISTS ix_att_status ON attendance (status);

CREATE TABLE IF NOT EXISTS attendance_corrections (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attendance_id   BIGINT NOT NULL,
  old_status      VARCHAR(13) NOT NULL CHECK (old_status IN ('PRESENT','LATE','ABSENT','EXCUSED','OFFICIAL_DUTY')),
  new_status      VARCHAR(13) NOT NULL CHECK (new_status IN ('PRESENT','LATE','ABSENT','EXCUSED','OFFICIAL_DUTY')),
  old_remarks     VARCHAR(255) NULL,
  new_remarks     VARCHAR(255) NULL,
  reason          VARCHAR(500) NOT NULL,
  status          VARCHAR(8) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  requested_by    INTEGER NULL,
  requested_at    TIMESTAMP(0) NOT NULL,
  reviewed_by     INTEGER NULL,
  reviewed_at     TIMESTAMP(0) NULL,
  review_comment  VARCHAR(500) NULL,
  CONSTRAINT fk_corr_att FOREIGN KEY (attendance_id) REFERENCES attendance(id) ON DELETE CASCADE,
  CONSTRAINT fk_corr_req FOREIGN KEY (requested_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_corr_rev FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_corr_status ON attendance_corrections (status, requested_at);
CREATE INDEX IF NOT EXISTS ix_corr_attendance ON attendance_corrections (attendance_id);

-- ---------------------------------------------------------------------
-- Audit trail and settings
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_logs (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NULL,
  username     VARCHAR(50) NULL,
  action       VARCHAR(60) NOT NULL,
  entity_type  VARCHAR(40) NOT NULL,
  entity_id    VARCHAR(40) NULL,
  summary      VARCHAR(500) NOT NULL,
  before_data  JSONB NULL,
  after_data   JSONB NULL,
  ip_address   VARCHAR(45) NULL,
  user_agent   VARCHAR(255) NULL,
  created_at   TIMESTAMP(3) NOT NULL DEFAULT timezone('UTC', now())
);
CREATE INDEX IF NOT EXISTS ix_audit_time ON audit_logs (created_at);
CREATE INDEX IF NOT EXISTS ix_audit_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS ix_audit_user ON audit_logs (user_id, created_at);
CREATE INDEX IF NOT EXISTS ix_audit_action ON audit_logs (action);

CREATE TABLE IF NOT EXISTS settings (
  setting_key    VARCHAR(60) PRIMARY KEY,
  setting_value  VARCHAR(1000) NOT NULL,
  updated_by     INTEGER NULL,
  updated_at     TIMESTAMP(0) NOT NULL DEFAULT timezone('UTC', now()),
  CONSTRAINT fk_settings_user FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['parties','constituencies','committees','mps','users','sittings','settings'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON %1$I', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t);
  END LOOP;
END $$;

